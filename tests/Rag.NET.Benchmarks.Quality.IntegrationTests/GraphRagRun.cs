/// <summary>
/// One end-to-end pass of <c>Rag.NET.GraphRag</c> over a list of MultiHop-RAG articles: extract,
/// detect communities, index, and search — the thing <see cref="GraphRagFunctionsTests"/> asserts
/// about over the pinned sixty-article slice, and the thing
/// <see cref="BeirGraphRagCorpusTests"/> measures nDCG@10 on over all 609.
/// <para>
/// <b>One class for both, and it was never a slice-shaped one.</b> <see cref="BuildAsync"/> has
/// always taken whatever documents it was handed; only the name said otherwise, and it was renamed
/// from <c>GraphRagSliceRun</c> rather than copied when the corpus run landed. A second copy that
/// ingested differently would compute extraction keys nothing wrote under, and that failure looks
/// exactly like an empty cache — which is the same reason the ingestion driver below is shared with
/// the generation tool rather than reimplemented.
/// </para>
/// <para>
/// <b>Every LLM call that decides what the graph contains is replayed, not made.</b> Extraction and
/// community reports both come out of <see cref="GraphExtractionCache"/> in refuse-on-miss mode —
/// out of two directories of it, generated by two runs of the same tool — so this class calls no
/// model at all and a machine without the cache fails loudly rather than quietly running a
/// different experiment.
/// </para>
/// <para>
/// <b>Global search's map-reduce is the one stage that stays on <see cref="PromptEchoChatClient"/>,
/// and the reason is not cost.</b> Its prompts are built from whichever community reports the
/// vector search returned, and ONNX Runtime dispatches its kernels on the available instruction
/// set, so a near-tie can order the other way on another machine. Caching those prompts would make
/// this guard fail refuse-on-miss everywhere but where they were recorded, for a reason with
/// nothing to do with GraphRAG. That file has the measurements behind it.
/// </para>
/// <para>
/// <b>The ingestion driver is shared with the generation tool</b>
/// (<see cref="GraphRagSliceIngestion"/>), because the cache key is the rendered prompt: a second
/// copy that chunked differently would compute keys nothing had written under, and the failure
/// would look exactly like an empty cache.
/// </para>
/// </summary>
internal sealed class GraphRagRun : IAsyncDisposable
{
    /// <summary>
    /// How many chunks the vector search hands the graph behaviors before they do their work.
    /// </summary>
    /// <remarks>
    /// Far above a production top-k, and both behaviors need it to be. Local search seeds its
    /// traversal from whichever results carry <c>graph_type = entity</c>, and global search does
    /// nothing at all unless a <c>graph_type = community_report</c> chunk is among them — so a
    /// top-5 over a store holding tens of thousands of chunks would exercise neither, and the guard
    /// would pass while measuring the dense retriever. This is the pipeline's candidate set, not
    /// its answer.
    /// <para>
    /// Internal rather than private because <see cref="BeirProtocol.GraphRagDepthControl"/> is a
    /// dense run at <i>this</i> depth, and a control that carried its own copy of the number could
    /// drift from the run it controls for without anything noticing.
    /// </para>
    /// </remarks>
    internal const int BaseTopK = 500;

    /// <summary>Document chunks embedded per call — a working-set bound, nothing more.</summary>
    private const int SlabSize = 512;

    /// <summary>
    /// A top-k larger than the store, for the diagnostic that asks where a community report ranks.
    /// <c>InMemoryVectorStore</c> bounds its heap by the corpus, so this reads "everything".
    /// </summary>
    private const int WholeStore = 1_000_000;

    /// <summary>The metadata value <c>CommunityDetectionBehavior</c> tags its reports with.</summary>
    private const string CommunityReportKind = "community_report";

    private readonly OnnxEmbeddingGenerator _generator;
    private readonly EmbeddingCache _embeddings;
    private readonly CachingEmbeddingGenerator _embedder;
    private readonly CachedGraphRagClient _chat;
    private readonly CachedGraphRagClient _reportChat;
    private readonly PromptEchoChatClient _globalChat = new();
    private readonly SqliteGraphStore _graphStore = new(":memory:");
    private readonly InMemoryVectorStore _vectorStore = new();

    /// <summary>
    /// Points the graph behaviours at <see cref="_vectorStore"/> — the run's ONE store.
    /// </summary>
    /// <remarks>
    /// <para>
    /// #247 separated the graph's chunks from the document chunks in the shipped library. This
    /// harness deliberately does not follow, and the reason is that its job is the opposite one:
    /// the <c>control</c> arm exists to measure what a SHARED store costs, and it cannot measure
    /// that from a split one. Pointing the chunk store at the same instance keeps every arm
    /// constructible and every pinned figure reproducible.
    /// </para>
    /// <para>
    /// The behaviours are unaffected by which store they are handed: local search asks for entity
    /// chunks and global search for community reports, and both get the same answers from this store
    /// that they got by sifting results before. What changed is where they ask, not what they find.
    /// </para>
    /// </remarks>
    private GraphChunkStore ChunkStore => field ??= new GraphChunkStore(_vectorStore);
    private readonly GraphRagOptions _options = GraphRagSliceIngestion.CreateOptions();
    /// <summary>
    /// Local-search options for the measured arms, pinning <c>PageRankWeight = 0.3</c> explicitly.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>Explicit because the library default changed under it.</b> This was <c>new()</c>, inheriting
    /// whatever <c>GraphRagRetrievalOptions</c> shipped — the type these properties lived on before
    /// it was renamed to <see cref="GraphRagGlobalSearchOptions"/> — which was 0.3 when every figure
    /// the <c>local</c> arm pins was measured. #239 changed that default to 0, so leaving this
    /// inheriting would have silently re-pointed those pins at a different configuration while their
    /// recorded text still said 0.3.
    /// </para>
    /// <para>
    /// A pinned measurement must not follow a library default. The figure describes one configuration
    /// on one day; the default is a product decision that moves independently. Setting it here keeps
    /// the recorded numbers meaning what they say, and the <c>local</c> arm now deliberately measures
    /// a <b>non-default</b> configuration — which is worth knowing when reading it, and is why
    /// <c>AnswerArm.Local</c> says so.
    /// </para>
    /// <para>
    /// The <c>PageRankWeight = 0</c> case is not lost: it is the ablation in
    /// <c>BeirGraphRagCorpusTests.Ablations_UnderTheGraphPath_PageRankWeightZero_AndGraphReach</c>,
    /// measured at nDCG@10 0.59658 — the candidate-set control to five decimals. The library ships
    /// no blend at all now, and that ablation is what its absence is equivalent to: a weight of zero
    /// already made the blend the identity, so removing it outright reproduces the same candidate
    /// set.
    /// </para>
    /// </remarks>
    private readonly LegacyPageRankOptions _retrievalOptions = new() { PageRankWeight = 0.3 };

    /// <summary>
    /// Global-search options at upstream defaults. Kept separate from <see cref="_retrievalOptions"/>
    /// because <see cref="GraphGlobalSearchBehavior"/> needs <see cref="GraphRagGlobalSearchOptions"/>
    /// members — <see cref="GraphRagGlobalSearchOptions.GlobalBatchSize"/> and
    /// <see cref="GraphRagGlobalSearchOptions.GlobalReportCandidates"/> — that
    /// <see cref="LegacyPageRankOptions"/> does not carry; global search reads none of the
    /// PageRank-blend properties, so the split changes nothing it measures.
    /// </summary>
    private readonly GraphRagGlobalSearchOptions _globalRetrievalOptions = new();

    /// <summary>
    /// Microsoft's local search as specified — <see cref="IGraphRagSearch"/>, not
    /// <see cref="LegacyPageRankLocalSearch"/> — over the run's own stores, at the upstream defaults.
    /// </summary>
    /// <remarks>
    /// Lazy because the builder is pure and the search holds only store references: constructing it
    /// eagerly in the constructor would validate <see cref="LocalSearchContextOptions"/> before the
    /// graph and chunk store exist, and re-constructing it per query would re-validate the same
    /// options 2,556 times for nothing. The chat client is <see cref="_chat"/> — unused by
    /// <see cref="GraphRagSearch.BuildLocalContextAsync(string, System.Threading.CancellationToken)"/>,
    /// so reusing it satisfies the constructor's type without opening a second dependency.
    /// </remarks>
    private readonly Lazy<GraphRagSearch> _localSpecSearch;

    private readonly Dictionary<string, HashSet<string>> _entityDocuments =
        new(StringComparer.OrdinalIgnoreCase);

    private readonly Dictionary<string, int> _articleChunksPerDocument =
        new(StringComparer.Ordinal);

    private GraphRagRun(
        OnnxEmbeddingGenerator generator,
        EmbeddingCache embeddings,
        GraphExtractionCache extractions,
        GraphExtractionCache reports)
    {
        _generator = generator;
        _embeddings = embeddings;
        _embedder = new CachingEmbeddingGenerator(generator, embeddings);
        _chat = new CachedGraphRagClient(
            extractions, inner: null, GraphExtractionModelIdentity.ExtractionTemperature);
        _reportChat = new CachedGraphRagClient(
            reports, inner: null, GraphExtractionModelIdentity.ExtractionTemperature);
        _localSpecSearch = new Lazy<GraphRagSearch>(() => new GraphRagSearch(
            _graphStore,
            ChunkStore,
            _vectorStore,
            _embedder,
            _chat,
            new LocalSearchContextOptions(),
            NullLogger<GraphRagSearch>.Instance));
    }

    /// <summary>Gets the finished graph: entities, relationships and communities.</summary>
    public GraphSnapshot Graph { get; private set; } = new([], [], []);

    /// <summary>Gets which slice articles each entity name was extracted from.</summary>
    /// <remarks>
    /// Read off the entity chunks the extraction behavior embedded, whose <c>DocumentId</c> is the
    /// article they came from — rather than off the graph store, whose entity table merges
    /// same-named entities into one row and keeps only the first article's id. The merge is what
    /// makes cross-article recurrence <i>useful</i>; it is also what makes it invisible from the
    /// store, so the guard counts it here where each occurrence is still separate.
    /// Case-insensitive, because the store's <c>name</c> column is <c>COLLATE NOCASE</c> and two
    /// spellings that merge there are one entity here too.
    /// </remarks>
    public IReadOnlyDictionary<string, HashSet<string>> EntityDocuments => _entityDocuments;

    /// <summary>Gets how many text chunks the run's articles were cut into.</summary>
    public int ChunkCount { get; private set; }

    /// <summary>Gets how many articles contributed at least one chunk of their own text.</summary>
    /// <remarks>
    /// Article chunks only, deliberately. It answers <see cref="BeirRunResult"/>'s
    /// <c>IndexedDocumentCount</c> question — "which documents are retrievable at all" — and an
    /// article that produced no chunk is unretrievable however many entities were extracted from
    /// it. Counting graph chunks here would hide exactly that.
    /// </remarks>
    public int IndexedDocumentCount => _articleChunksPerDocument.Count;

    /// <summary>Gets the largest number of article chunks any one article was cut into.</summary>
    /// <remarks>
    /// The Real protocol's <c>MaxChunksPerDocument</c>, re-derived here off the same chunker, so
    /// the two legs' reported shapes are comparable rather than merely similarly named.
    /// </remarks>
    public int MaxChunksPerDocument { get; private set; }

    /// <summary>Gets how many entity and relationship chunks extraction embedded and indexed.</summary>
    public int GraphChunkCount { get; private set; }

    /// <summary>Gets how many community reports were replayed, embedded and indexed.</summary>
    public int CommunityReportCount { get; private set; }

    /// <summary>Gets how many extraction requests were served from the cache.</summary>
    public long ReplayedRequests => _chat.Calls;

    /// <summary>Gets how many map and reduce calls global search has made through the stub.</summary>
    public long GlobalSearchCalls => _globalChat.Calls;

    /// <summary>Gets how many community reports were replayed from the report cache.</summary>
    /// <remarks>
    /// One per community, and every one of them the text <c>openai/gpt-4o-mini</c> returned when
    /// the generation tool ran <c>--stage reports</c> — not a synthesised head of the prompt, which
    /// is what this counted while the reports came from <see cref="PromptEchoChatClient"/>. A
    /// number below the community count means detection asked for fewer reports than there are
    /// communities; the run cannot make any of them.
    /// </remarks>
    public long ReplayedReports => _reportChat.Calls;

    /// <summary>
    /// Gets the character length of the largest community-report prompt this run built.
    /// </summary>
    /// <remarks>
    /// A deliberately tracked figure, measured on every run so the cost of the largest community is
    /// a measurement rather than an anecdote — it moved from 1,806,352 characters to 195,446 when
    /// Leiden stopped over-merging, and to under 50,000 when
    /// <c>GraphRagOptions.MaxCommunityReportPromptLength</c> bounded it. It comes off the cached
    /// client now that the report stage is replayed rather than echoed; the measurement moved with
    /// the prompts, it was not dropped with the stub.
    /// </remarks>
    public long LongestReportPrompt => _reportChat.LongestPrompt;

    /// <summary>Gets how many times a search has gone to the vector store through this run.</summary>
    /// <remarks>
    /// The evidence that global search fetched its own community reports: one call means it worked
    /// with the candidate set it was handed, two means it found no report there and went back for
    /// them with a metadata filter.
    /// </remarks>
    public int RetrievalCalls { get; private set; }

    /// <summary>
    /// Extracts the slice into a graph, detects communities over it, and indexes everything.
    /// </summary>
    /// <param name="documents">The slice's articles, in corpus order.</param>
    /// <param name="generator">The embedder; the caller disposes it.</param>
    /// <param name="embeddings">The vector cache.</param>
    /// <param name="extractions">The extraction cache, opened refuse-on-miss.</param>
    /// <param name="reports">
    /// The community-report cache, opened refuse-on-miss over
    /// <see cref="GraphExtractionCache.ReportsDirectoryName"/>. Separate from
    /// <paramref name="extractions"/> because the two stages are generated by two runs of the tool
    /// and a machine can have one and not the other — in which case this run must say which.
    /// </param>
    /// <param name="cancellationToken">Cancels the run.</param>
    /// <returns>The finished run, ready to search.</returns>
    public static async Task<GraphRagRun> BuildAsync(
        IReadOnlyList<BeirDocument> documents,
        OnnxEmbeddingGenerator generator,
        EmbeddingCache embeddings,
        GraphExtractionCache extractions,
        GraphExtractionCache reports,
        CancellationToken cancellationToken)
    {
        var run = new GraphRagRun(generator, embeddings, extractions, reports);
        await run.IngestAsync(documents, cancellationToken);
        await run.DetectCommunitiesAsync(cancellationToken);

        return run;
    }

    /// <summary>Runs local search for one query and returns what it produced.</summary>
    public async Task<IReadOnlyList<SearchResult>> LocalSearchAsync(
        string query, CancellationToken cancellationToken) =>
        (await LocalSearchWithCandidatesAsync(query, cancellationToken)).Results;

    /// <summary>
    /// Runs local search for one query and returns <b>both</b> what the dense retrieval underneath
    /// it found and what the behavior made of that.
    /// </summary>
    /// <param name="query">The query text.</param>
    /// <param name="cancellationToken">Cancels the search.</param>
    /// <returns>The candidate set and the blended result.</returns>
    /// <remarks>
    /// <b>The candidate set is the control the graph behavior is differenced against, and without
    /// it a corpus-scale nDCG cannot be attributed to anything.</b> Two things change at once when
    /// the graph path is measured against the dense one: the store gains a quarter of a million
    /// entity, relationship and community-report chunks, and
    /// <see cref="LegacyPageRankLocalSearch"/> reorders and deduplicates whatever comes out of it.
    /// Scoring the candidates as well as the results separates them — same query, same store, same
    /// scan, one extra pooling — so a difference from the Real leg's figure can be laid at the door
    /// of the store's contents or of the behavior rather than at "GraphRAG" as an undivided thing.
    /// It costs one <see cref="DocumentRanking"/> pass per query and no retrieval.
    /// </remarks>
    public Task<GraphLocalSearchOutcome> LocalSearchWithCandidatesAsync(
        string query, CancellationToken cancellationToken) =>
        LocalSearchWithCandidatesAsync(query, _retrievalOptions, cancellationToken);

    /// <summary>
    /// <see cref="LocalSearchWithCandidatesAsync(string, CancellationToken)"/> under retrieval
    /// options the caller chooses instead of the run's defaults.
    /// </summary>
    /// <param name="query">The query text.</param>
    /// <param name="retrievalOptions">The options the behavior is constructed with.</param>
    /// <param name="cancellationToken">Cancels the search.</param>
    /// <returns>The candidate set and the blended result.</returns>
    /// <remarks>
    /// Exists for the ablations issue #239 asks for — chiefly <c>PageRankWeight = 0</c>, which
    /// the code says turns the behavior into a re-ordering-free pass over its input. The
    /// candidate set is retrieved identically whatever the options say, since the options only
    /// reach the behavior; that is what makes two runs under different options a comparison of
    /// the behavior alone.
    /// </remarks>
    public async Task<GraphLocalSearchOutcome> LocalSearchWithCandidatesAsync(
        string query, LegacyPageRankOptions retrievalOptions, CancellationToken cancellationToken)
    {
        var behavior = new LegacyPageRankLocalSearch(_graphStore, retrievalOptions, ChunkStore, _embedder);
        IReadOnlyList<SearchResult> candidates = [];

        var results = await behavior.HandleAsync(
            CreateContext(query),
            cancellationToken,
            async (context, token) => candidates = await RetrieveAsync(context, token));

        return new GraphLocalSearchOutcome(candidates, results);
    }

    /// <summary>The specification-faithful local search context for one query, rendered.</summary>
    /// <remarks>
    /// Constructed once and reused across queries: the builder is pure and the search holds only
    /// store references, so a per-query instance would re-validate the options 2,556 times and
    /// change nothing.
    /// </remarks>
    /// <param name="query">The question.</param>
    /// <param name="ct">Cancels the embedding call and the store reads.</param>
    /// <returns>The rendered context.</returns>
    public async Task<string> LocalSpecContextAsync(string query, CancellationToken ct)
    {
        var context = await _localSpecSearch.Value.BuildLocalContextAsync(query, ct);
        return context.Text;
    }

    /// <summary>
    /// The documents the graph reaches from a candidate set's seed entities and that the candidate
    /// set itself does not name — the expansion <see cref="LegacyPageRankLocalSearch"/> does not
    /// perform, done here so it can be measured.
    /// </summary>
    /// <param name="candidates">The dense candidate set for one query.</param>
    /// <param name="retrievalOptions">
    /// Supplies <see cref="LegacyPageRankOptions.LocalTopEntities"/> and
    /// <see cref="LegacyPageRankOptions.LocalSearchDepth"/>, so the seeds and the walk are the
    /// behavior's own.
    /// </param>
    /// <param name="cancellationToken">Cancels the walk.</param>
    /// <returns>
    /// The document ids the walk reaches that no candidate chunk belongs to, ordered by the highest
    /// PageRank of the entity that reached each, ties by document id. Documents the candidate set
    /// already names are excluded, so the caller appends this to its own pooled ranking.
    /// </returns>
    /// <remarks>
    /// <para>
    /// <b>The behavior traverses and adds nothing</b> (#239): its walk harvests PageRank scores and
    /// its output is its input re-scored. So "does the graph find documents dense missed" cannot be
    /// asked through the behavior at all — it has to be asked here, of the walk's reach. Seeds are
    /// exactly what <c>CollectTopEntities</c> takes, the walk is exactly
    /// <see cref="IGraphStore.GetNeighborsAsync"/> at the configured depth, and a neighbour's
    /// documents are the articles its entity chunks were extracted from
    /// (<see cref="EntityDocuments"/>) — the same credit an entity chunk earns when it retrieves.
    /// </para>
    /// <para>
    /// Appended below the caller's own pooled candidate ranking, the expansion can only <i>add</i>:
    /// a Recall@k over that list against the same k over the candidates alone is the graph's
    /// contribution and nothing else. Which is also its limit — this measures reach, not ranking,
    /// and it says nothing about where a real expansion would place what it adds.
    /// </para>
    /// </remarks>
    public async Task<IReadOnlyList<string>> ExpandDocumentsAsync(
        IReadOnlyList<SearchResult> candidates,
        LegacyPageRankOptions retrievalOptions,
        CancellationToken cancellationToken)
    {
        var seeds = candidates
            .Where(r => r.Chunk.Metadata.TryGetValue("graph_type", out var kind) && kind == "entity")
            .OrderByDescending(r => r.Score)
            .Take(retrievalOptions.LocalTopEntities)
            .ToList();

        var reached = new Dictionary<string, double>(StringComparer.Ordinal);
        for (var i = 0; i < seeds.Count; i++)
        {
            if (!seeds[i].Chunk.Metadata.TryGetValue("graph_entity_name", out var nameValue))
            {
                continue;
            }

            var neighbours = await _graphStore.GetNeighborsAsync(
                nameValue.ToString(), retrievalOptions.LocalSearchDepth, cancellationToken);
            for (var j = 0; j < neighbours.Count; j++)
            {
                if (!_entityDocuments.TryGetValue(neighbours[j].Name, out var documents))
                {
                    continue;
                }

                foreach (var document in documents)
                {
                    reached[document] = Math.Max(
                        reached.GetValueOrDefault(document, double.NegativeInfinity),
                        neighbours[j].PageRankScore);
                }
            }
        }

        var named = new HashSet<string>(StringComparer.Ordinal);
        for (var i = 0; i < candidates.Count; i++)
        {
            _ = named.Add(candidates[i].Chunk.DocumentId.Value);
        }

        return reached
            .Where(pair => !named.Contains(pair.Key))
            .OrderByDescending(pair => pair.Value)
            .ThenBy(pair => pair.Key, StringComparer.Ordinal)
            .Select(pair => pair.Key)
            .ToList();
    }

    /// <summary>
    /// Runs global search for one query over the same candidate set local search gets.
    /// </summary>
    /// <remarks>
    /// <b>There is no longer a second, filtered variant of this, and its removal is the point.</b>
    /// The guard used to reach the map-reduce by handing the behavior a candidate set it had
    /// restricted to community reports itself, because a plain dense top-500 over this slice
    /// contains none and the behavior did nothing without them. A guard doing by hand what the
    /// library should do is a guard testing itself, so the behavior now re-enters retrieval with
    /// its own metadata filter and this — the unfiltered call any caller would make — is what gets
    /// asserted.
    /// </remarks>
    public Task<IReadOnlyList<SearchResult>> GlobalSearchAsync(
        string query, CancellationToken cancellationToken) =>
        GlobalSearchAsync(query, _globalChat, cancellationToken);

    /// <summary>
    /// Runs global search for one query with the map/reduce going through
    /// <paramref name="chatClient"/> instead of the run's prompt-echo stub.
    /// </summary>
    /// <param name="query">The query text.</param>
    /// <param name="chatClient">The client the map and reduce calls go to.</param>
    /// <param name="cancellationToken">Cancels the search.</param>
    /// <returns>The synthesised answer chunk first, then the non-report candidates.</returns>
    /// <remarks>
    /// The stub is right for the guard, whose reason for not caching global search's prompts is
    /// recorded on <see cref="GraphRagRun"/>. The answer-level evaluation (Phase 5.2.2) needs the
    /// real map/reduce, replayed from its own cache — which became possible when #241 made the
    /// report order a function of the query rather than of the process.
    /// </remarks>
    public async Task<IReadOnlyList<SearchResult>> GlobalSearchAsync(
        string query, IChatClient chatClient, CancellationToken cancellationToken)
    {
        var behavior = new GraphGlobalSearchBehavior(chatClient, _globalRetrievalOptions, ChunkStore, _embedder);

        return await behavior.HandleAsync(CreateContext(query), cancellationToken, RetrieveAsync);
    }

    /// <summary>
    /// Where the best-scoring community report sits in the full ranking for a query, or -1 when
    /// none is indexed. The diagnostic behind <see cref="GlobalSearchOverReportsAsync"/>'s remark.
    /// </summary>
    public async Task<int> FirstCommunityReportRankAsync(
        string query, CancellationToken cancellationToken)
    {
        var vectors = await BeirHarness.EmbedAsync(
            _generator, _embeddings, [query], cancellationToken);
        var everything = await _vectorStore.SearchAsync(
            vectors[0], new SearchOptions { TopK = WholeStore }, cancellationToken);

        for (var i = 0; i < everything.Count; i++)
        {
            if (everything[i].Chunk.Metadata.TryGetValue("graph_type", out var kind)
                && kind == CommunityReportKind)
            {
                return i;
            }
        }

        return -1;
    }

    /// <inheritdoc/>
    public async ValueTask DisposeAsync()
    {
        _vectorStore.Dispose();
        _chat.Dispose();
        _reportChat.Dispose();
        _globalChat.Dispose();
        _embedder.Dispose();
        await _graphStore.DisposeAsync();
    }

    /// <summary>
    /// Chunks and extracts every article, indexing the chunks themselves alongside the entity and
    /// relationship chunks extraction produced.
    /// </summary>
    /// <remarks>
    /// The article chunks are indexed too, and they have to be: without them the store holds only
    /// entity descriptions and community reports, and "local search retrieved a relevant document"
    /// would be a statement about which entities happened to be summarised rather than about
    /// retrieval. A real pipeline stores both; this indexes both.
    /// </remarks>
    private async Task IngestAsync(
        IReadOnlyList<BeirDocument> documents, CancellationToken cancellationToken)
    {
        for (var i = 0; i < documents.Count; i++)
        {
            var chunks = await GraphRagSliceIngestion.ChunkAsync(documents[i], cancellationToken);
            ChunkCount += chunks.Count;
            RecordArticleChunkShape(documents[i], chunks.Count);

            var graphChunks = await GraphRagSliceIngestion.ExtractAsync(
                documents[i], chunks, _chat, _embedder, _graphStore, _options, cancellationToken);
            GraphChunkCount += graphChunks.Count;

            RecordEntityDocuments(graphChunks);
            await _vectorStore.StoreAsync(graphChunks, cancellationToken);
            await IndexArticleChunksAsync(chunks, cancellationToken);
        }
    }

    /// <summary>Notes how many chunks one article's own text produced.</summary>
    /// <remarks>
    /// A document yielding no chunk is never recorded, which is the point: an empty article is
    /// unretrievable and <see cref="IndexedDocumentCount"/> has to say so rather than counting
    /// every article the loop walked past.
    /// </remarks>
    private void RecordArticleChunkShape(BeirDocument document, int chunkCount)
    {
        if (chunkCount == 0)
        {
            return;
        }

        _articleChunksPerDocument.TryGetValue(document.Id, out var existing);
        var total = existing + chunkCount;
        _articleChunksPerDocument[document.Id] = total;

        if (total > MaxChunksPerDocument)
        {
            MaxChunksPerDocument = total;
        }
    }

    /// <summary>Notes which article each extracted entity name came from.</summary>
    private void RecordEntityDocuments(IReadOnlyList<EmbeddedChunk> graphChunks)
    {
        for (var i = 0; i < graphChunks.Count; i++)
        {
            var chunk = graphChunks[i].Chunk;
            if (!chunk.Metadata.TryGetValue("graph_entity_name", out var name))
            {
                continue;
            }

            var entity = name.ToString();
            if (!_entityDocuments.TryGetValue(entity, out var documents))
            {
                documents = new HashSet<string>(StringComparer.Ordinal);
                _entityDocuments[entity] = documents;
            }

            _ = documents.Add(chunk.DocumentId.Value);
        }
    }

    /// <summary>Embeds and indexes one article's own chunks, through the vector cache.</summary>
    private async Task IndexArticleChunksAsync(
        IReadOnlyList<TextChunk> chunks, CancellationToken cancellationToken)
    {
        for (var start = 0; start < chunks.Count; start += SlabSize)
        {
            var end = Math.Min(start + SlabSize, chunks.Count);
            var texts = new string[end - start];
            for (var i = start; i < end; i++)
            {
                texts[i - start] = chunks[i].Text;
            }

            var vectors = await BeirHarness.EmbedAsync(
                _generator, _embeddings, texts, cancellationToken);

            var stored = new EmbeddedChunk[end - start];
            for (var i = start; i < end; i++)
            {
                stored[i - start] = new EmbeddedChunk
                {
                    Chunk = chunks[i],
                    Embedding = vectors[i - start],
                };
            }

            await _vectorStore.StoreAsync(stored, cancellationToken);
        }
    }

    /// <summary>Runs community detection once over the finished graph and indexes the reports.</summary>
    /// <remarks>
    /// <b>Through the shared driver, with a refuse-on-miss client, for one reason.</b> The report
    /// cache is keyed on the prompt <c>CommunityDetectionBehavior</c> renders, and that prompt is a
    /// function of this graph — its communities, their members' merged descriptions, their PageRank
    /// order. Detection therefore has to run here exactly as it ran in the tool that filled the
    /// cache: same driver, same options, same graph, same order. Anything else misses on every key.
    /// </remarks>
    private async Task DetectCommunitiesAsync(CancellationToken cancellationToken)
    {
        var reports = await GraphRagSliceIngestion.DetectCommunitiesAsync(
            _reportChat, _embedder, _graphStore, _options, cancellationToken);

        CommunityReportCount = reports.Count;
        await _vectorStore.StoreAsync(reports, cancellationToken);

        Graph = await _graphStore.GetFullGraphAsync(cancellationToken);
    }

    /// <summary>The retrieval context both searches run in.</summary>
    private static RetrievalContext CreateContext(string query) =>
        new()
        {
            Query = query,
            Options = new RetrievalOptions { TopK = BaseTopK },
        };

    /// <summary>
    /// The dense retrieval both graph behaviors sit in front of: embed the query through the cache,
    /// scan the store, return the candidates.
    /// </summary>
    /// <remarks>
    /// <b>It reads <see cref="RetrievalOptions.MetadataFilter"/> and
    /// <see cref="RetrievalOptions.TopK"/> off the context because the pipeline's own
    /// <c>VectorStoreBehavior</c> does.</b> This method stands in for that behavior, and a stand-in
    /// that ignored half its contract would make the guard measure something the library does not
    /// do — which matters now that <c>GraphGlobalSearchBehavior</c> re-enters retrieval with a
    /// filtered context of its own. Hard-coding the top-k here, as this once did, would have made
    /// that second call indistinguishable from the first and the behavior look unreachable when it
    /// is not.
    /// </remarks>
    private async ValueTask<IReadOnlyList<SearchResult>> RetrieveAsync(
        RetrievalContext context, CancellationToken cancellationToken)
    {
        RetrievalCalls++;
        var vectors = await BeirHarness.EmbedAsync(
            _generator, _embeddings, [context.Query], cancellationToken);

        return await _vectorStore.SearchAsync(
            vectors[0],
            new SearchOptions
            {
                TopK = context.Options.TopK,
                MetadataFilter = context.Options.MetadataFilter,
            },
            cancellationToken);
    }

    /// <summary>What one local search saw and what it made of it.</summary>
    /// <param name="Candidates">
    /// What the dense retrieval underneath the behavior returned — the pipeline's candidate set,
    /// <see cref="BaseTopK"/> chunks deep, before any graph work.
    /// </param>
    /// <param name="Results">
    /// What <see cref="LegacyPageRankLocalSearch"/> returned: the same chunks blended with PageRank
    /// and deduplicated. It can hold <b>fewer</b> entries than
    /// <paramref name="Candidates"/> — see <see cref="BeirGraphRagCorpusTests"/>, which measures by
    /// how many and why that matters to the metric.
    /// </param>
    internal sealed record GraphLocalSearchOutcome(
        IReadOnlyList<SearchResult> Candidates, IReadOnlyList<SearchResult> Results);
}
